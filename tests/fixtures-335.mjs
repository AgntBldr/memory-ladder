export function withEnv(values, run) {
  const saved = Object.fromEntries(Object.keys(values).map(key => [key, process.env[key]]));
  Object.assign(process.env, values);
  try { return run(); }
  finally { for (const [key, value] of Object.entries(saved)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; } }
}
// A repository elsewhere, on another branch, that an inherited GIT_DIR and GIT_WORK_TREE point at.
export function elsewhere(f) { const dir = repo(f, 'elsewhere', 'main-elsewhere'); return {GIT_DIR: path.join(dir, '.git'), GIT_WORK_TREE: dir}; }
export const refusedBy = (result, holder, file = 'current-state.md') => {
  assert.equal(result.status, 1, result.stdout + result.stderr);
  assert.match(result.stderr, new RegExp(`upgrade refused: 1 files pending in other sessions: .* claims ${file.replace(/[.]/g, '\\.')}; see memory-session list; nothing written`), result.stderr);
  if (holder) assert.ok(result.stderr.includes(holder), result.stderr);
  assert.ok(!/upgrade backup:/.test(result.stdout), 'no backup was written');
};

