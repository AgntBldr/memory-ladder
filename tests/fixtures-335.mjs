// A foreign main checkout whose KIT.local.json names its own memory, and its linked worktree, which inherited
// GIT_DIR and GIT_WORK_TREE point at.
export function foreignWorktree(f) {
  const main = repo(f, 'foreign', 'main'), foreignMemory = path.join(f.root, 'foreign-memory'), wt = path.join(f.root, 'foreign-wt');
  put(path.join(foreignMemory, 'MEMORY.md'), '# Foreign memory\n'); f.git(foreignMemory, 'init', '-q');
  put(path.join(main, 'scripts/memory/KIT.local.json'), JSON.stringify({memoryDir: foreignMemory}) + '\n');
  f.git(main, 'add', '-A'); f.git(main, 'commit', '-qm', 'foreign');
  f.git(main, 'worktree', 'add', '-q', wt);
  return {foreignMemory, env: {...f.env, GIT_DIR: f.git(wt, 'rev-parse', '--absolute-git-dir'), GIT_WORK_TREE: wt}};
}

// The same environment for every other session-aware writer, with the foreign checkout naming a memory folder that
// does not exist: a writer that followed the inherited GIT_DIR would fail, or find no memory, or create that folder.
export function foreignMissing(f) {
  const {foreignMemory, env} = foreignWorktree(f);
  fs.rmSync(foreignMemory, {recursive: true, force: true});
  return {foreignMemory, env};
}
export const writer = (f, name, args, env) => f.exec(process.execPath, [path.join(f.target, 'scripts/memory', name), ...args], {env});

// This project's memory with a backup remote and 12 commits that were never pushed: the gate's repo.ahead FAIL.
export function aheadMemory(f) {
  const bare = path.join(f.root, 'backup.git'), branch = f.git(f.memory, 'branch', '--show-current');
  f.git(f.root, 'init', '-q', '--bare', bare);
  f.git(f.memory, 'remote', 'add', 'origin', bare); f.git(f.memory, 'push', '-q', '-u', 'origin', branch);
  for (let i = 0; i < 12; i++) { put(path.join(f.memory, `note-${i}.md`), `---\nname: note-${i}\ndescription: Unpushed note ${i}.\n---\nbody\n`); f.git(f.memory, 'add', '.'); f.git(f.memory, 'commit', '-qm', `unpushed ${i}`); }
  return {bare, branch, head: f.git(f.memory, 'rev-parse', 'HEAD')};
}
