export const J = JSON.stringify;
// Lock files by name, spelled here so these tests do not depend on the predicate they check.
export const lockName = name => /^\.memory\.lock/i.test(name);
export const lockless = snapshot => Object.fromEntries(Object.entries(snapshot).filter(([file]) => !file.split('/').some(lockName)));
export const hookOf = dir => path.join(dir, '.git/hooks/pre-commit');
export const bytes = file => fs.existsSync(file) ? fs.readFileSync(file).toString('base64') : null;
export const state = f => ({project: tree(f.target), memory: lockless(tree(f.memory)), hook: bytes(hookOf(f.memory))});
export const upgrade = (f, root, args = [], env) => f.exec(process.execPath, [path.join(root, 'scripts/upgrade.mjs'), '--target', f.target, ...args], env ? {env} : {});
export const backupOf = result => /upgrade backup: (.+)/.exec(result.stdout)[1].trim();
export function repo(f, name, branch) { const dir = path.join(f.root, name); fs.mkdirSync(dir); f.git(dir, 'init', '-q', '-b', branch); return dir; }
// Another session (its own checkout on its own branch) claims memory files; returns the checkout as its ledger names it.
export function claim(f, files = ['current-state.md'], name = 'other') {
  const checkout = repo(f, name, 'feature-' + name);
  claimFiles({memoryDir: f.memory, repo: checkout, files, by: 'test'});
  return fs.realpathSync.native(checkout);
}
export function driver(f, root, hooks, prelude = '', opts = {}) {
  return put(path.join(f.root, 'driver.mjs'), `import fs from 'node:fs';
import {upgrade} from ${J(pathToFileURL(path.join(root, 'scripts/upgrade.mjs')).href)};
${prelude}
process.exitCode = upgrade(${J({target: f.target, 'live-memory': true, ...opts})}, ${J(root)}, {${hooks}});
`);
}
