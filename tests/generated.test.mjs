test('S2 concurrent capture allocates distinct numbers after a four-digit letter identity', async t => {
  const f = fixture(t); f.lesson('1000b');
  const run = title => new Promise((resolve, reject) => {
    const script = `import fs from 'node:fs';
      import {newLesson} from ${JSON.stringify(pathToFileURL(path.join(engine, 'memory-lesson.mjs')).href)};
      const dir = ${JSON.stringify(f.memoryDir)}, root = ${JSON.stringify(f.root)}, title = ${JSON.stringify(title)};
      const sleep = ms => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
      fs.writeFileSync(root + '/' + title + '.ready', '');
      const deadline = Date.now() + 5000;
      while (fs.readdirSync(root).filter(f => f.endsWith('.ready')).length < 2) { if (Date.now() > deadline) throw Error('barrier timeout'); sleep(10); }
      const read = fs.readdirSync;
      fs.readdirSync = (name, ...args) => { const result = read(name, ...args); if (name === dir) sleep(300); return result; };
      console.log(newLesson({kind: 'mistake', memoryDir: dir, route: 'craft', title}));`;
    const child = spawn(process.execPath, ['--input-type=module', '-e', script]);
    let out = '', err = ''; child.stdout.on('data', b => out += b); child.stderr.on('data', b => err += b);
    child.on('error', reject); child.on('close', code => resolve({code, out, err}));
  });
  const results = await Promise.all([run('First title'), run('Second title')]);
  for (const r of results) assert.equal(r.code, 0, r.err);
  const files = fs.readdirSync(f.memoryDir).filter(x => /^lesson-100[12]-/.test(x));
  assert.equal(files.length, 2);
  const allocated = results.map(r => path.basename(r.out.trim()));
  assert.deepEqual(allocated.map(file => /^lesson-(\d+)-/.exec(file)[1]).sort(), ['1001', '1002']);
  assert.deepEqual(files.sort(), allocated.sort());
  for (const file of files) assert.equal(parseFrontmatter(fs.readFileSync(path.join(f.memoryDir, file), 'utf8')).data.description, 'TODO');
});

