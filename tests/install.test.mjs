function installWithBaseline(t,f) {
  // Resolve HOME only inside the fixture's child process.
  return ok(f.install()).stdout;
}

test('K.8 install writes a template brain index before the first gate',t=>{
  const f=fixture(t),index=put(path.join(f.target,'brain/00-system/index.md'),'# Index\n\nStatic index, regenerated by scripts/memory/brain-index.mjs --write. old\n');
  put(path.join(f.target,'brain/00-system/memory-ladder.md'),'# Memory ladder\n');
  put(path.join(f.target,'brain/01-pillars/pil-example.md'),'---\nid: pil-example\ntype: pillar\nsummary: Example pillar\n---\n# Example\n');
  const output=installWithBaseline(t,f);
  assert.match(output,/install: brain index written/);
  assert.doesNotMatch(output,/repo\.brain-index/);
  assert.match(read(index),/Static index, regenerated by scripts\/memory\/brain-index\.mjs --write/);
  assert.match(read(index),/\[memory-ladder\.md\]\(memory-ladder\.md\)/);
  const result=ok(f.cli('scripts/memory/memory-check.mjs',['--repo',f.target,'--json'],f.target));
  assert.ok(!JSON.parse(result.stdout).findings.some(x=>x.check==='repo.brain-index'));
});

test('K.8 install without a brain leaves it absent',t=>{
  const f=fixture(t),output=installWithBaseline(t,f);
  assert.ok(!fs.existsSync(path.join(f.target,'brain')));
  assert.doesNotMatch(output,/install: brain index written/);
});

test('K.8 dry run reports the brain index and preserves every fixture byte',t=>{
  const f=fixture(t),index=put(path.join(f.target,'brain/00-system/index.md'),'# Index\n\nStatic index, regenerated by scripts/memory/brain-index.mjs --write. old\n');
  put(path.join(f.target,'brain/01-pillars/pil-example.md'),'---\nid: pil-example\ntype: pillar\n---\n');
  const before=tree(f.root,{git:true}),r=ok(f.install(['--dry-run']));
  assert.match(r.stdout,/^DRY brain index$/m);
  assert.equal(read(index),'# Index\n\nStatic index, regenerated by scripts/memory/brain-index.mjs --write. old\n');
  assert.deepEqual(tree(f.root,{git:true}),before);
});

for(const script of ['install','upgrade']) for(const flag of ['--help','-h']) test(`K.8 ${script} ${flag} lists all accepted options without writes`,t=>{
  const f=fixture(t);
  put(path.join(f.target,'.claude/settings.json'),'{invalid');
  const before=tree(f.root,{git:true});
  for(const args of [[flag],['--target',f.target,flag],['--unknown',flag]]) {
    const r=ok(f.cli(`scripts/${script}.mjs`,args));
    assert.match(r.stdout,new RegExp(`Usage: node scripts/${script}\\.mjs`));
    for(const option of ['--target','--memory-dir','--restore','--dry-run','--check','--force-skills','--backup','--help']) {
      assert.ok(r.stdout.split('\n').some(line=>line.trimStart().startsWith(option+' ')),option);
    }
    assert.match(r.stdout,/-h/);
    assert.doesNotMatch(r.stdout,/--ratchet-pins/);
    assert.equal(r.stderr,'');
    assert.deepEqual(tree(f.root,{git:true}),before);
  }
});

