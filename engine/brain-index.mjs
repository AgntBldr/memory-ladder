import fs from 'node:fs';
import path from 'node:path';
import { args, isDirect, loadConfig, repoRoot, read, brainPaths, parseFrontmatter, fmGet, utf8Bytes } from './lib.mjs';

const cmp = (a, b) => a < b ? -1 : a > b ? 1 : 0;
export function generateIndex({ repo = repoRoot(), config = loadConfig() } = {}) {
  const nodes = brainPaths(repo).map(file => {
    const { data } = parseFrontmatter(read(path.join(repo, 'brain', file)));
    const updated = String(fmGet(data, 'updated') ?? '');
    return { file, folder: path.posix.dirname(file), id: fmGet(data, 'id'), type: fmGet(data, 'type'), status: fmGet(data, 'status') ?? '', summary: String(fmGet(data, 'summary') ?? ''), updated: /^\d{4}-\d{2}-\d{2}$/.test(updated) ? updated : '' };
  }).filter(n => n.id && n.type).sort((a, b) => cmp(a.id, b.id));
  const groups = new Map();
  for (const n of nodes) { if (!groups.has(n.folder)) groups.set(n.folder, []); groups.get(n.folder).push(n); }
  const domains = [...new Set(nodes.filter(n => n.file.startsWith('03-knowledge/')).map(n => n.file.split('/')[1]))].sort();
  const recent = ns => [...ns].sort((a, b) => cmp(b.updated, a.updated) || cmp(a.id, b.id));
  const summary = (n, max) => n.summary.replace(/\s+/g, ' ').slice(0, max);
  const updated = nodes.map(n => n.updated).sort().at(-1) || '';
  let fm = parseFrontmatter(read(path.join(repo, config.caps.brainIndex.path))).raw;
  if (fm) fm = fm.replace(/^updated:.*$/m, `updated: ${updated}`);
  const lines = [...(fm ? [fm, ''] : []), '# Index', '', `Static index, regenerated by scripts/memory/brain-index.mjs --write. ${nodes.length} typed nodes; ${domains.length} knowledge domains.`, '', '## System'];
  for (const file of config.caps.brainIndex.systemFiles ?? ['AGENTS.md', 'schema.md', 'edge-cases.md', 'skills-index.md', 'log.md', 'index-all.md', 'agents-background.md', 'memory-ladder.md']) {
    if (fs.existsSync(path.join(repo, 'brain/00-system', file))) lines.push(`- [${file}](${file})`);
  }
  lines.push('', '## Pillar');
  for (const n of nodes.filter(n => n.type === 'pillar')) lines.push(`[[${n.id}]] — ${summary(n, 120)}`);
  lines.push('', '## Projects');
  for (const n of nodes.filter(n => n.type === 'project')) lines.push(`[[${n.id}]] (${n.status}) — ${summary(n, 120)}`);
  const tasks = nodes.filter(n => n.type === 'task');
  lines.push(`Tasks: ${tasks.length} (${tasks.filter(n => ['done', 'completed', 'archived'].includes(n.status)).length} done/completed/archived). Events: ${nodes.filter(n => n.type === 'event').length}.`, '', '## Knowledge');
  for (const domain of domains) { const ns = nodes.filter(n => n.file.startsWith(`03-knowledge/${domain}/`)); lines.push(`**${domain}** (${ns.length}): ${recent(ns).slice(0, 3).map(n => `[[${n.id}]]`).join(', ')}`); }
  lines.push('', '## Other');
  for (const folder of ['04-playbooks', '05-sources', '06-people', '99-inbox']) { const ns = nodes.filter(n => n.file.startsWith(folder + '/')); lines.push(`${folder} (${ns.length}): ${(ns.length <= 6 ? ns : recent(ns).slice(0, 6)).map(n => `[[${n.id}]]`).join(', ')}`); }
  lines.push('', '## Shared core', `brain/_shared: ${nodes.filter(n => n.file.startsWith('_shared/')).length} nodes copied from the shared core; their edges to other vaults' pillars are external (gate --json externalEdges).`, '');
  const sections = [];
  for (const line of lines) {
    if (!sections.length || line.startsWith('## ')) sections.push({lines: [], removed: 0});
    sections.at(-1).lines.push(line);
  }
  const render = () => sections.map(s => [...s.lines, ...(s.removed ? [`${s.removed} more; see [all nodes](index-all.md).`, ''] : [])].flat()).flat().join('\n');
  let index = render();
  while (utf8Bytes(index) > config.caps.brainIndex.maxBytes) {
    const candidates = sections.slice(1).filter(s => s.lines.some((line, i) => i > 0 && line.trim()));
    candidates.sort((a, b) => utf8Bytes(b.lines.join('\n')) - utf8Bytes(a.lines.join('\n')));
    if (!candidates.length) break;
    const section = candidates[0], i = section.lines.findLastIndex((line, i) => i > 0 && line.trim());
    section.lines.splice(i, 1); section.removed++; index = render();
  }
  if (utf8Bytes(index) > config.caps.brainIndex.maxBytes) index = `# Index\n\n${nodes.length} more: [all nodes](index-all.md).\n`;
  if (utf8Bytes(index) > config.caps.brainIndex.maxBytes) throw new Error(`brain index ${utf8Bytes(index)} bytes exceeds ${config.caps.brainIndex.maxBytes}`);
  const all = ['# All nodes', '', `Static index, regenerated by scripts/memory/brain-index.mjs --write. ${nodes.length} typed nodes.`, ''];
  for (const folder of [...groups.keys()].sort()) all.push(`## ${folder}`, ...groups.get(folder).map(n => `- [[${n.id}]] (${n.type}, ${n.status}) — ${summary(n, 160)}`), '');
  return { index, all: all.join('\n') };
}
export function main(argv = process.argv.slice(2)) {
  try {
    const opts = args(argv.filter(arg => arg !== '--write'));
    if (argv.includes('--write') && opts.check) throw new Error('choose --write or --check');
    const repo = path.resolve(opts.repo || repoRoot()), config = opts.config ? JSON.parse(read(opts.config)) : loadConfig();
    const output = generateIndex({ repo, config }), allFile = path.join(repo, config.caps.brainIndex.allPath);
    // The first write creates a system page that must also appear in the final index.
    if (argv.includes('--write') && !fs.existsSync(allFile)) {
      fs.mkdirSync(path.dirname(allFile), { recursive: true });
      fs.writeFileSync(allFile, output.all);
      try { output.index = generateIndex({ repo, config }).index; }
      catch (error) { fs.unlinkSync(allFile); throw error; }
    }
    const pairs = [[config.caps.brainIndex.path, output.index], [config.caps.brainIndex.allPath, output.all]];
    if (opts.check) { const ok = pairs.every(([file, text]) => fs.existsSync(path.join(repo, file)) && read(path.join(repo, file)) === text); console.log(ok ? 'brain index: fresh' : 'brain index: stale or missing'); return ok ? 0 : 1; }
    if (argv.includes('--write')) for (const [file, text] of pairs) { fs.mkdirSync(path.dirname(path.join(repo, file)), { recursive: true }); fs.writeFileSync(path.join(repo, file), text); }
    else process.stdout.write(output.index);
    return 0;
  } catch (error) { console.error(`brain-index: ${error.message}`); return 1; }
}
if (isDirect(import.meta.url)) process.exitCode = main();
