export const generatedMarker = '<!-- generated by memory-index.mjs; edit the lessons, not this file -->';
export const isGenerated = text => text.split(/\r?\n/, 1)[0] === generatedMarker;
export const lessonIdentity = file => /^lesson-(\d{3,}[a-z]*)-.+\.md$/.exec(file)?.[1];
export const lessonField = (data, key) => Object.hasOwn(data.metadata ?? {}, key) ? data.metadata[key] : data[key];
export const gateCheckIds = source => [...new Set([...source.matchAll(/\badd\([^,\n]+,\s*['"]([a-z][a-z.-]*)['"]|\bsize\(['"]([^'"]+)['"]|\blineCaps\(\w+,\s*['"]([^'"]+)['"]|\[['"][a-zA-Z]+['"],\s*['"]([a-z]+\.[a-z-]+)['"]\]/g)].map(m => m[1] ?? m[2] ?? m[3] ?? m[4]))].sort();
export const KINDS = ['mistake', 'practice', 'observation'];
export const CAUSES = ['slip', 'not-recalled', 'rule-wrong', 'new-case'];
export const REPEAT_ENTRY = /^(\d{4}-\d{2}-\d{2}) (slip|not-recalled|rule-wrong|new-case|legacy): (\S.*)$/;
export const failSentence = ({count, id}) => `repeated ${count} times with no recorded decision; record one with memory-lesson.mjs enforce ${id} "<hook|check|hard-rule|lesson-only> <where>" (lesson-only with a reason counts)`;
export const enforceSentence = ({count, last, id}) => `repeated ${count} times (last ${last}); decide where the mistake is visible: in the command (hook), in a file (check), or only in judgment (hard-rule card or lesson-only), then run memory-lesson.mjs enforce ${id} "<hook|check|hard-rule|lesson-only> <where>"`;
export const routes = data => {
  const value = lessonField(data, 'route');
  return value === undefined || value === null ? [] : Array.isArray(value) ? value : [value];
};
// Shared by the gate and measurement. Costs include navigation pages, not the target.
export function ladderWalk(memoryDir, files = memoryFiles(memoryDir)) {
  const router = files.find(f => f.special === 'router'), found = new Map();
  const pages = new Map(files.filter(f => f.special === 'index').map(f => [pathKey(memoryDir, f.file), f]));
  const queue = [];
  const visit = (key, bytes, hop) => {
    if (found.has(key) && found.get(key).bytes <= bytes) return;
    found.set(key, {bytes, hop});
    if (pages.has(key)) queue.push({key, bytes, hop});
  };
  for (const link of mdLinks(resolveRouter(router?.body ?? '', memoryDir))) visit(pathKey(memoryDir, link), router.bytes, 'direct');
  while (queue.length) {
    const current = queue.shift(), page = pages.get(current.key);
    if (found.get(current.key).bytes !== current.bytes) continue;
    for (const link of mdLinks(page.text)) {
      const key = pathKey(memoryDir, link), next = pages.get(key);
      // After the first index, only catalogs can continue navigation.
      if (next && !/-all(?:-\d+)?\.md$/i.test(next.file)) continue;
      visit(key, current.bytes + page.bytes, current.hop === 'direct' ? 'index' : 'catalog');
    }
  }
  return found;
}
export function resolveRouter(router, memoryDir) {
  return router.split(/(?<=\n)/).map(line => !isRoutingRow(line) ? line : line.replace(/`(INDEX-[A-Za-z0-9][A-Za-z0-9-]*\.md)`/g, (token, file) => {
    if (!memoryDir) return token;
    try { if (fs.statSync(path.join(memoryDir, file)).isFile()) return `[${file}](${file})`; } catch {}
    return token;
  })).join('');
}
// A routing entry starts with its link (optionally list/table markup), or an
// explicit OPEN/trigger directive. A link embedded in state prose is not a row.
export function isRoutingRow(line) {
  const at=line.search(/\[[^\]]*\]\(INDEX-|`INDEX-/);
  if (at<0) return false;
  const prefix=line.slice(0,at), plain=prefix.replace(/^\s*(?:>\s*)?(?:(?:[-*+]|\d+[.)]|#{1,6})\s*)?(?:\[[ xX]\]\s*)?\|?\s*/, '');
  return !plain || /^\s*(?:[-*+]\s|\d+[.)]\s|\|)/.test(prefix) || /^[^()[\]]+:\s*$/.test(plain) || /^(?:OPEN|BEFORE|WHEN)\b/i.test(plain) || /^\s*#{1,6}\s/.test(prefix) || /^\[[^\]]*\]\([^)]*\)\s*[\u2014\u2013-]?\s*read\b/i.test(plain);
}
export const triggerVocabulary = String.raw`\b(?:OPEN|BEFORE|WHEN|TRIGGER)\b`;
export const hasTrigger = text => text.split(/\r?\n/).some(line =>
  !/^\s*(?:#{1,6}\s|<!--)/.test(line) &&
  new RegExp(triggerVocabulary, 'i').test(line.replace(/\[[^\]]*\]\([^)]*\)|`[^`]*`/g, '')));
export function routerFamilies(router, memoryDir) {
  router = resolveRouter(router, memoryDir);
  const families = new Map();
  for (const line of router.split(/\r?\n/)) {
    if (!isRoutingRow(line)) continue;
    const match = /\[[^\]]*\]\(INDEX-([A-Za-z0-9][A-Za-z0-9-]*)\.md\)(.*)$/.exec(line);
    if (match && !/-all(?:-\d+)?$/.test(match[1])) {
      const family = indexFamily('INDEX-' + match[1] + '.md');
      families.set(family, [families.get(family), line.trim()].filter(Boolean).join("\n"));
    }
  }
  return new Map([...families].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}
const clean = value => String(value ?? '').replace(/[\r\n]+/g, ' ');
const compare = (a, b) => {
  const x = lessonIdentity(a.file), y = lessonIdentity(b.file);
  if (!x || !y) return x ? 1 : y ? -1 : a.file < b.file ? -1 : a.file > b.file ? 1 : 0;
  const nx = BigInt(/^\d+/.exec(x)[0]), ny = BigInt(/^\d+/.exec(y)[0]);
  return nx < ny ? -1 : nx > ny ? 1 : a.file < b.file ? -1 : a.file > b.file ? 1 : 0;
};
// Keep the immutable link prefix even when it alone exceeds the warning cap.
const cut = (text, cap) => {
  if (!text || text.length <= cap) return text;
  const available = Math.max(0, cap - 1);
  const candidate = text.slice(0, available + 1);
  const links = [...text.matchAll(/\[[^\]]*\]\([^)]*\)/g)];
  const boundaries = [...candidate.matchAll(/\s/gu)].filter(m => !links.some(link => m.index >= link.index && m.index < link.index + link[0].length));
  const boundary = boundaries.at(-1)?.index ?? -1;
  let shortened;
  if (boundary >= 20) shortened = candidate.slice(0, boundary);
  else {
    shortened = '';
    for (const point of Array.from(text)) {
      if (shortened.length + point.length > available) break;
      shortened += point;
    }
  }
  return shortened.replace(/[\s,;:\-]+$/gu, '') + '…';
};
function hotFamilies(router) {
  const families = new Map();
  for (const line of router.split(/\r?\n/)) {
    if (!isRoutingRow(line)) continue;
    const match = /\[[^\]]*\]\(INDEX-([A-Za-z0-9][A-Za-z0-9-]*)\.md\)(.*)$/.exec(line);
    if (!match || /-all(?:-\d+)?$/.test(match[1])) continue;
    const family = indexFamily('INDEX-' + match[1] + '.md');
    if (families.has(family) && family !== match[1] && (hasTrigger(families.get(family)) || !hasTrigger(line))) continue;
    const after = match[2].trim();
    const before = line.slice(0, match.index).replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/^\s*(?:[-*+] |\d+[.)] )/, '').replace(/^\s*(?:#+\s+|>\s+)/, '').replace(/^\s*\[[ xX]\]\s+/, '').replace(/\|/g, ' ').trim().replace(/[:;\-—–]+\s*$/u, '').trim();
    const sentence = hasTrigger(before) && !hasTrigger(after) ? [before, /\p{L}/u.test(after) ? after : ''].filter(Boolean).join(' ') : /\p{L}/u.test(after) ? after : /\p{L}/u.test(before) ? before : '';
    if (!hasTrigger(families.get(family) ?? "") || hasTrigger(sentence)) families.set(family, sentence);
  }
  return new Map([...families].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}
const entry = (f, cap) => {
  const id = lessonIdentity(f.file);
  const repeats = lessonField(f.data, 'repeats');
  const prefix = `- [${id ? '#' + id : clean(fmGet(f.data, 'name') ?? f.file)}](${f.file}) — ` + (Array.isArray(repeats) && repeats.length ? `(${repeats.length} repeats) ` : '') + (lessonField(f.data, 'kind') === 'practice' ? '(practice) ' : lessonField(f.data, 'kind') === 'observation' ? '(observed) ' : '');
  const text = clean(id ? lessonField(f.data, 'hook') ?? fmGet(f.data, 'description') : fmGet(f.data, 'description'));
  return prefix + cut(text, cap - prefix.length) + '\n';
};
export function generateMemoryIndex({memoryDir, config = loadConfig(), files = memoryFiles(memoryDir)}) {
  const families = hotFamilies(resolveRouter(files.find(f => f.file === 'MEMORY.md')?.text ?? '', memoryDir));
  const pages = {}, overflow = [];
  const row = f => entry(f, config.caps.index.warnLineChars ?? 300);
  const budget = config.caps.index.hotBytes ?? 8192, cap = config.caps.index.failBytesAbsolute;
  for (const [family, sentence] of families) {
    const members = files.filter(f => !f.special && routes(f.data).includes(family)).sort(compare);
    const superseded = new Set(members.flatMap(f => lessonField(f.data, 'supersedes') ?? []));
    const topics = members.filter(f => !lessonIdentity(f.file));
    const lessons = members.filter(f => lessonIdentity(f.file));
    const active = lessons.filter(f => !superseded.has(f.file));
    const pins = active.filter(f => lessonField(f.data, 'pin') === true);
    const newest = active.filter(f => lessonField(f.data, 'pin') !== true).reverse();
    const header = `${generatedMarker}\n# INDEX: ${family}\n\n${sentence ? cut(sentence, config.caps.index.warnLineChars ?? 300) + '\n\n' : ''}`;
    const footer = count => `\n${count} older lessons: [catalog](INDEX-${family}-all.md) or memory-recall.\n`;
    let hot = header + [...topics, ...pins].map(row).join(''), selected = pins.length;
    if (utf8Bytes(hot + footer(lessons.length - selected)) > budget) overflow.push(family);
    for (const f of newest) {
      const line = row(f);
      if (utf8Bytes(hot + line + footer(lessons.length - selected - 1)) <= budget) { hot += line; selected++; }
    }
    pages[`INDEX-${family}.md`] = hot + (!sentence && hot === header ? footer(lessons.length - selected).slice(1) : footer(lessons.length - selected));
    const chunks = [[]];
    const catalogName = n => `INDEX-${family}-all${n === 1 ? '' : '-' + n}.md`;
    const catalog = (lines, n, next = true) => `${generatedMarker}\n# INDEX: ${family} — catalog ${n}\n\n${lines.join('')}\n${next ? `[Next](${catalogName(n + 1)})\n` : ''}`;
    for (const member of members) {
      const line = row(member), n = chunks.length, chunk = chunks.at(-1);
      if (utf8Bytes(catalog([line], n)) > cap) throw new Error('catalog entry exceeds absolute cap: ' + member.file);
      if (utf8Bytes(catalog([...chunk, line], n)) > cap) chunks.push([line]);
      else chunk.push(line);
    }
    chunks.forEach((chunk, i) => { pages[catalogName(i + 1)] = catalog(chunk, i + 1, i < chunks.length - 1); });
  }
  const removed = files.filter(f => f.special === 'index' && isGenerated(f.text) && !Object.hasOwn(pages, f.file)).map(f => f.file);
  return {pages, removed, overflow};
}
export function writeMemoryIndex(options) {
  return withMemoryLock(options.memoryDir, () => {
    const result = generateMemoryIndex(options);
    const files = memoryFiles(options.memoryDir);
    for (const file of Object.keys(result.pages)) {
      const existing = files.find(f => f.file === file);
      if (existing && !existing.stub && !isGenerated(existing.text)) throw new Error('run the route migration first; refusing to overwrite ' + file);
    }
    for (const [file, text] of Object.entries(result.pages)) writeText(path.join(options.memoryDir, file), text);
    for (const file of result.removed) fs.unlinkSync(path.join(options.memoryDir, file));
    return result;
  }, {lock: options.lock});
}
export function main(argv = process.argv.slice(2)) {
  try {
    const opts = args(argv.filter(x => x !== '--write')), loc = locations(opts);
    if (!loc.memoryDir || !fs.existsSync(path.join(loc.memoryDir, 'MEMORY.md'))) { console.log('memory index: no existing router'); return 0; }
    if (argv.includes('--write') && opts.check) throw new Error('choose --write or --check');
    const options = {...loc, config: opts.config ? JSON.parse(read(opts.config)) : loadConfig()};
    const result = argv.includes('--write') ? writeMemoryIndex(options) : generateMemoryIndex(options);
    const stale = result.removed.length || Object.entries(result.pages).some(([file, text]) => read(path.join(loc.memoryDir, file)).replace(/\r\n/g, '\n') !== text);
    console.log(`memory index: ${Object.keys(result.pages).length} pages${opts.check && stale ? '; stale; run memory-index.mjs --write' : ''}`);
    return opts.check && stale ? 1 : 0;
  } catch (error) { console.error('memory-index: ' + error.message); return 1; }
}
if (isDirect(import.meta.url)) process.exitCode = main();
