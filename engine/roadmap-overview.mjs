import fs from 'node:fs';
import path from 'node:path';
import { args, isDirect, loadConfig, repoRoot, read, parseFrontmatter, walkMd } from './lib.mjs';
import { splitSections } from './memory-conserve.mjs';

const compareCodePoints = (a, b) => {
  const left = Array.from(a, c => c.codePointAt(0)), right = Array.from(b, c => c.codePointAt(0));
  for (let i = 0; i < Math.min(left.length, right.length); i++) if (left[i] !== right[i]) return left[i] - right[i];
  return left.length - right.length;
};
export function generateOverview({ repo = repoRoot(), config = loadConfig() } = {}) {
  const roadmap = splitSections(read(path.join(repo, config.caps.roadmap.path)));
  const preamble = roadmap.find(s => s.kind === 'preamble')?.text || '';
  const release = [], labels = /^(Last updated:|Current release candidate:|Latest published release:|Working version in the repo:)/;
  let active = false;
  for (const line of preamble.split('\n')) {
    if (labels.test(line)) active = true;
    else if (!line.trim() || /^[^\s:]+(?:[^:]*):/.test(line)) active = false;
    if (active) release.push(line);
  }
  const historyPath = config.caps.roadmapHistory.path;
  const lines = ['# Roadmap overview', '', `Generated by scripts/memory/roadmap-overview.mjs from ${config.caps.roadmap.path}, ${config.caps.shelf.path}/ and ${historyPath}. Do not edit; regenerate with --write.`, '', '## Release state', ...release, ''];
  const open = roadmap.find(s => /^## Open work/.test(s.heading));
  if (open) {
    lines.push(open.heading);
    const groups = []; let group;
    for (const line of open.text.split('\n')) {
      if (line.startsWith('### ')) { group = { name: line.slice(4), items: [] }; groups.push(group); }
      else if (group && /^(- |\d+[a-z]?\. )/.test(line)) { const first = Array.from(line.replaceAll('**', '')); group.items.push(first.length > 140 ? first.slice(0, 140).join('') + '…' : first.join('')); }
    }
    for (const g of groups) lines.push(`### ${g.name} (${g.items.length} ${g.items.length === 1 ? 'item' : 'items'})`, ...g.items);
    lines.push('');
  }
  const programs = roadmap.filter(s => /^## Active/.test(s.heading)).map(s => `- ${s.heading.slice(3)}`);
  lines.push('## Active programs', ...(programs.length ? programs : ['None live.']), '', '## Shelf');
  const shelf = walkMd(path.join(repo, config.caps.shelf.path)).map(file => {
    const data = parseFrontmatter(read(path.join(repo, config.caps.shelf.path, file))).data;
    return { ...data, file, name: String(data.name ?? path.basename(file, path.extname(file))) };
  }).sort((a, b) => compareCodePoints(a.name, b.name) || compareCodePoints(a.file, b.file));
  const cell = value => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
  if (shelf.length) lines.push('| Program | Shelved | Review | Source |', '| --- | --- | --- | --- |', ...shelf.map(s => `| ${[s.name, s.shelved, s.review, s.moved_from].map(cell).join(' | ')} |`));
  else lines.push('Empty.');
  const history = splitSections(read(path.join(repo, historyPath))).filter(s => s.kind === 'section').map(s => s.heading.slice(3));
  lines.push('', '## History', `${historyPath} holds ${history.length} sections; first "${history[0] ?? ''}", last "${history.at(-1) ?? ''}".`, '');
  return lines.join('\n');
}
export function main(argv = process.argv.slice(2)) {
  try {
    const opts = args(argv.filter(arg => arg !== '--write'));
    if (argv.includes('--write') && opts.check) throw new Error('choose --write or --check');
    const repo = path.resolve(opts.repo || repoRoot()), config = loadConfig(), output = generateOverview({ repo, config });
    const file = path.join(repo, config.caps.roadmapOverview.path);
    if (opts.check) { const ok = fs.existsSync(file) && read(file) === output; console.log(ok ? 'roadmap overview: fresh' : 'roadmap overview: stale or missing'); return ok ? 0 : 1; }
    if (argv.includes('--write')) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, output); }
    else process.stdout.write(output);
    return 0;
  } catch (error) { console.error(`roadmap-overview: ${error.message}`); return 1; }
}
if (isDirect(import.meta.url)) process.exitCode = main();
